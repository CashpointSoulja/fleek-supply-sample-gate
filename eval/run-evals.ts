import { readFileSync, writeFileSync } from "node:fs";
import { DEFAULT_THRESHOLDS, evaluate } from "../src/engine/engine";
import { SEED_INSPECTIONS } from "../src/engine/seeds";
import type { Inspection } from "../src/engine/types";

interface Case { id: string; name: string; base: number; patch: Partial<Inspection>; expect: string }
const { cases } = JSON.parse(readFileSync(new URL("./cases.json", import.meta.url), "utf8")) as { cases: Case[] };

let passed = 0;
const lines: string[] = ["| Case | Scenario | Expected | Got | Pilot units | Result |", "|---|---|---|---|---|---|"];
for (const c of cases) {
  const base = SEED_INSPECTIONS[c.base];
  const insp: Inspection = { ...base, ...c.patch, demand: { ...base.demand, ...(c.patch.demand ?? {}) } };
  const e = evaluate(insp, DEFAULT_THRESHOLDS);
  const got = e.valid ? e.recommendation! : "INVALID";
  const ok = got === c.expect;
  if (ok) passed++;
  lines.push(`| ${c.id} | ${c.name} | ${c.expect} | ${got} | ${e.pilot?.units ?? "-"} | ${ok ? "PASS" : "FAIL"} |`);
  console.log(`${ok ? "PASS" : "FAIL"} ${c.id} ${c.name}: expected ${c.expect}, got ${got}`);
}
const summary = `${passed}/${cases.length} cases matched the expected decision (default thresholds).`;
console.log(summary);
writeFileSync(new URL("./results.md", import.meta.url), `# Eval results\n\nGenerated by \`npm run evals\` against \`eval/cases.json\` with default thresholds. Synthetic cases; illustrative only.\n\n${lines.join("\n")}\n\n**${summary}**\n`);
if (passed !== cases.length) process.exit(1);
